import assert from 'node:assert/strict';
import { previewSnapshot, beginTestSession, endTestSession, resetTesting, recordTime, recordFeature, recordReflection, addWord, addDesign, finishMeasurement, sessionSummary } from '../src/participation/store.js';
resetTesting();
recordTime('/object/1926',10);recordFeature('Photos');recordReflection('1926','color');
assert.deepEqual(previewSnapshot().pages,{});
assert.deepEqual(previewSnapshot().features,{});
assert.deepEqual(previewSnapshot().terms,{});
assert.equal(beginTestSession({adult:false,analytics:true}),false);
assert.equal(beginTestSession({adult:true,analytics:false}),false);
assert.equal(previewSnapshot().session,null);
assert.equal(beginTestSession({adult:true,analytics:true}),true);
const sessionId=previewSnapshot().session.id;
recordReflection('1926','The colour and color, soft fabric');
recordReflection('873ab','black');
assert.deepEqual(previewSnapshot().terms['1926'],{color:2,soft:1,fabric:1});
assert.deepEqual(previewSnapshot().terms['873ab'],{black:1});
recordTime('/object/1926',2.5,sessionId);recordTime('/object/1926',3,sessionId);
assert.equal(previewSnapshot().pages['/object/1926'],5.5);
recordFeature('Photos');assert.equal(previewSnapshot().features.Photos,1);
finishMeasurement();
const frozen=sessionSummary();
recordTime('/object/1926',99,sessionId);recordFeature('Photos');recordReflection('1926','newword');
assert.deepEqual(sessionSummary(),frozen);
assert.equal(frozen.pages['/object/1926'],6);
frozen.terms['1926'].color=999;
assert.equal(sessionSummary().terms['1926'].color,2);
endTestSession();recordFeature('Photos');assert.deepEqual(previewSnapshot().features,{});
assert.deepEqual(previewSnapshot().terms,{});assert.equal(previewSnapshot().session,null);
beginTestSession({adult:true,analytics:true});assert.notEqual(previewSnapshot().session.id,sessionId);
recordTime('/object/1926',10,sessionId);assert.deepEqual(previewSnapshot().pages,{});
addWord('flowing');addDesign({title:'Test',cases:{Gathers:['1926']}});
assert.equal(previewSnapshot().words.length,1);assert.equal(previewSnapshot().designs.length,1);
resetTesting();assert.deepEqual(previewSnapshot(),{words:[],designs:[],enabled:false,session:null,pages:{},features:{},terms:{}});
console.log('PASS: measurements off by default, garment-specific normalized counts, timing accumulation, stop/reset, session previews.');
